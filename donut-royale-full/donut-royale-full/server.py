def now():
    return datetime.now(timezone.utc)

def pw_hash(password, salt):
    return hashlib.pbkdf2_hmac("sha256", password.encode(), bytes.fromhex(salt), 260000).hex()

class PGConnection:
    def __init__(self):
        self.conn = psycopg.connect(os.environ["DATABASE_URL"], row_factory=dict_row, connect_timeout=12)
    def __enter__(self):
        self.conn.__enter__()
        return self
    def __exit__(self, *args):
        return self.conn.__exit__(*args)
    def execute(self, sql, params=()):
        return self.conn.execute(sql.replace("?", "%s").replace(" COLLATE NOCASE", ""), params)

def db_open():
    if USE_POSTGRES:
        return PGConnection()
    db = sqlite3.connect(DB, timeout=30)
    db.row_factory = sqlite3.Row
    db.execute("PRAGMA busy_timeout=30000")
    return db

def seed_extra_admin(db):
    """Create the configured staff account once; never reset an existing password or balance."""
    name = os.getenv("EXTRA_ADMIN_USERNAME", "").strip()
    password = os.getenv("EXTRA_ADMIN_PASSWORD", "")
    if not re.fullmatch(r"[A-Za-z0-9_]{3,16}", name) or len(password) < 8:
        return
    existing = db.execute("SELECT id,role FROM users WHERE lower(username)=lower(?)", (name,)).fetchone()
    if existing:
        return
    salt = secrets.token_hex(16)
    db.execute("INSERT INTO users(username,salt,pw,role,balance,approval) VALUES(?,?,?,'admin',0,'approved')",
               (name, salt, pw_hash(password, salt)))


def setup_postgres():
    with db_open() as db:
        db.execute("""CREATE TABLE IF NOT EXISTS users (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            username TEXT NOT NULL, salt TEXT NOT NULL, pw TEXT NOT NULL,
            role TEXT NOT NULL DEFAULT 'player', balance BIGINT NOT NULL DEFAULT 0,
            approval TEXT NOT NULL DEFAULT 'approved')""")
        db.execute("CREATE UNIQUE INDEX IF NOT EXISTS users_username_lower_idx ON users (lower(username))")
        db.execute("CREATE TABLE IF NOT EXISTS admin_chat (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id), message TEXT NOT NULL, created TIMESTAMP DEFAULT CURRENT_TIMESTAMP)")
        db.execute("""CREATE TABLE IF NOT EXISTS tickets (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id BIGINT NOT NULL REFERENCES users(id),
            kind TEXT NOT NULL, amount BIGINT NOT NULL DEFAULT 0,
            message TEXT NOT NULL DEFAULT '', status TEXT NOT NULL DEFAULT 'open',
            response TEXT NOT NULL DEFAULT '', created TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            handled BIGINT DEFAULT 0)""")
        db.execute("""CREATE TABLE IF NOT EXISTS sessions (
            token_hash TEXT PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id),
            expires TEXT NOT NULL)""")
        db.execute("""CREATE TABLE IF NOT EXISTS bot_payment_events (
            event_id TEXT PRIMARY KEY, player TEXT NOT NULL, amount BIGINT NOT NULL,
            raw_message TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'unverified',
            created TIMESTAMP DEFAULT CURRENT_TIMESTAMP)""")
        db.execute("""CREATE TABLE IF NOT EXISTS bot_deposit_credits (
            event_id TEXT PRIMARY KEY REFERENCES bot_payment_events(event_id),
            ticket_id BIGINT NOT NULL UNIQUE REFERENCES tickets(id),
            user_id BIGINT NOT NULL REFERENCES users(id),
            amount BIGINT NOT NULL, created TIMESTAMP DEFAULT CURRENT_TIMESTAMP)""")
        db.execute("UPDATE users SET approval='approved' WHERE approval IS NULL OR approval!='approved'")
        db.execute("CREATE TABLE IF NOT EXISTS mines_games (user_id BIGINT PRIMARY KEY REFERENCES users(id), bet BIGINT NOT NULL, mines INTEGER NOT NULL, bombs TEXT NOT NULL, revealed TEXT NOT NULL DEFAULT '[]', created TIMESTAMP DEFAULT CURRENT_TIMESTAMP)")
        # Retired Mines game: return any still-locked stakes once, then clear rounds.
        db.execute("UPDATE users SET balance=balance+(SELECT COALESCE(SUM(bet),0) FROM mines_games WHERE user_id=users.id) WHERE id IN (SELECT user_id FROM mines_games)")
        db.execute("DELETE FROM mines_games")
        seed_owner(db)
        seed_extra_admin(db)
        db.execute("DELETE FROM sessions WHERE expires<=?", (now().isoformat(),))

