class Handler(BaseHTTPRequestHandler):
    def send_json(self, status, payload, cookie=None):
        data = json.dumps(payload, ensure_ascii=False, default=str).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(data)))
        self.send_header("Cache-Control", "no-store")
        self.send_header("X-Content-Type-Options", "nosniff")
        if cookie:
            self.send_header("Set-Cookie", cookie)
        self.end_headers()
        self.wfile.write(data)

    def fail(self, status, message):
        self.send_json(status, {"error": message})

    def payload(self):
        try:
            length = int(self.headers.get("Content-Length", "0"))
            if length < 0 or length > 20000:
                return {}
            data = json.loads(self.rfile.read(length))
            return data if isinstance(data, dict) else {}
        except (ValueError, UnicodeDecodeError):
            return {}

    def token(self):
        try:
            cookies = SimpleCookie()
            cookies.load(self.headers.get("Cookie", ""))
            return cookies["session"].value if "session" in cookies else None
        except Exception:
            return None

    def me(self):
        token = self.token()
        if not token:
            return None
        with db_open() as db:
            row = db.execute("""
                SELECT u.id,u.username,u.role,u.balance FROM sessions s
                JOIN users u ON u.id=s.user_id
                WHERE s.token_hash=? AND s.expires>?
            """, (hashlib.sha256(token.encode()).hexdigest(), now().isoformat())).fetchone()
        return dict(row) if row else None

    def cookie(self, token):
        cookie = "session=" + token + "; Path=/; HttpOnly; SameSite=Lax; Max-Age=31536000"
        if os.getenv("RENDER") or os.getenv("COOKIE_SECURE") == "1":
            cookie += "; Secure"
        return cookie

    def do_GET(self):
        path = urlparse(self.path).path
        if path == "/":
            path = "/index.html"
        if path in ("/index.html", "/coin-heads.png", "/coin-tails.png", "/style.css", "/app.js", "/coin-sonic-hd.svg", "/coin-tails-hd.svg"):
            file = BASE / path.lstrip("/")
            if not file.is_file():
                return self.fail(404, "File not found")
            data = file.read_bytes()
            kind = mimetypes.guess_type(str(file))[0] or "application/octet-stream"
            self.send_response(200)
            self.send_header("Content-Type", kind + ("; charset=utf-8" if kind.startswith("text/") else ""))
            self.send_header("Content-Length", str(len(data)))
            self.send_header("Cache-Control", "no-store" if path == "/index.html" else "no-cache")
            self.end_headers()
            self.wfile.write(data)
            return
        if path == "/api/me":
            return self.send_json(200, {"user": self.me()})
        if path == "/api/rules":
            return self.send_json(200, {"max_bet": MAX_BET, "win_chance_percent": 40,
                                        "loss_chance_percent": 60, "payout_multiplier": 2,
                                        "all_in_always_loses": True})
        user = self.me()
        if not user:
            return self.fail(401, "Please log in")
        if path == "/api/mines":
            with db_open() as db:
                state = mines_state(db, user["id"])
            return self.send_json(200, state)
        if path == "/api/tickets":
            with db_open() as db:
                if user["role"] in ("owner", "admin"):
                    rows = db.execute("""SELECT t.*,u.username FROM tickets t JOIN users u ON u.id=t.user_id
                                         WHERE t.status='open' ORDER BY t.id DESC""").fetchall()
                else:
                    rows = db.execute("""SELECT t.*,u.username FROM tickets t JOIN users u ON u.id=t.user_id
                                         WHERE t.status='open' AND t.user_id=? ORDER BY t.id DESC""",
                                      (user["id"],)).fetchall()
            return self.send_json(200, {"tickets": [dict(r) for r in rows]})
        if path == "/api/admin-chat":
            if user["role"] not in ("owner", "admin"):
                return self.fail(403, "Staff only")
            with db_open() as db:
                rows = db.execute("SELECT c.id,c.user_id,c.message,c.created,u.username FROM admin_chat c JOIN users u ON u.id=c.user_id ORDER BY c.id DESC LIMIT 100").fetchall()
            return self.send_json(200, {"messages": [dict(row) for row in reversed(rows)]})
        if path == "/api/users":
            if user["role"] not in ("owner", "admin"):
                return self.fail(403, "Not allowed")
            with db_open() as db:
                rows = db.execute("SELECT id,username,role,balance FROM users ORDER BY id DESC").fetchall()
            return self.send_json(200, {"users": [dict(r) for r in rows]})
        return self.fail(404, "Not found")

