def withdrawal_config():
    # Do not send any payment until an actual outgoing receipt format is verified.
    try:
        if os.getenv("AUTO_WITHDRAW_ENABLED") != "1":
            return None
        cutoff = _deposit_time(os.environ["AUTO_WITHDRAW_START_UTC"])
        pattern = re.compile(os.environ["AUTO_WITHDRAW_RECEIPT_REGEX"], re.I)
        if not {"player", "amount"} <= set(pattern.groupindex):
            return None
        cap = int(os.getenv("AUTO_WITHDRAW_MAX_AMOUNT", "1000"))
        daily = int(os.getenv("AUTO_WITHDRAW_DAILY_LIMIT", "5000"))
        if cap < 0 or daily < 0 or (cap and daily and daily < cap) or cutoff > now():
            return None
        return cutoff, pattern, cap, daily
    except (KeyError, ValueError, re.error):
        return None


def auto_credit_deposit(db, event_id, player, amount, raw_message, received_at=None):
    """Opt-in only. Requires independent validation of the payment source before enabling."""
    if os.getenv("AUTO_DEPOSIT_ENABLED") != "1" or not os.getenv("AUTO_DEPOSIT_START_UTC"):
        return "unverified"
    if USE_POSTGRES:
        db.execute("SELECT pg_advisory_xact_lock(2026112207)")
    try:
        cutoff = _deposit_time(os.environ["AUTO_DEPOSIT_START_UTC"])
    except ValueError:
        return "unverified"
    event = db.execute("SELECT created FROM bot_payment_events WHERE event_id=?", (event_id,)).fetchone()
    if not event or _deposit_time(event["created"]) < cutoff:
        return "unverified"
    receipt_time = _deposit_time(event["created"])
    if received_at is not None:
        try:
            if not isinstance(received_at, str) or len(received_at) > 40:
                return "needs_review"
            captured = _deposit_time(received_at)
            if captured < cutoff or abs((receipt_time - captured).total_seconds()) > 60:
                return "needs_review"
            receipt_time = min(receipt_time, captured)
        except (ValueError, TypeError, OverflowError):
            return "needs_review"
    # Bound automatic credit risk. Larger events require manual verification.
    try:
        limit = int(os.getenv("AUTO_DEPOSIT_MAX_AMOUNT", "1000000"))
        daily_limit = int(os.getenv("AUTO_DEPOSIT_DAILY_LIMIT", "5000000"))
    except ValueError:
        return "needs_review"
    if limit < 1 or daily_limit < 1 or amount > limit:
        return "needs_review"
    receipt = re.fullmatch(r"(\.?[A-Za-z0-9_]{3,16}) paid you \$\s*([0-9,]+(?:\.[0-9]+)?)\s*([KMBT])?", raw_message, re.I)
    if not receipt or receipt.group(1).casefold() != player.casefold():
        return "needs_review"
    try:
        multiplier = {"": 1, "K": 10**3, "M": 10**6, "B": 10**9, "T": 10**12}[str(receipt.group(3) or "").upper()]
        parsed = Decimal(receipt.group(2).replace(",", "")) * multiplier
        if parsed != amount:
            return "needs_review"
    except (InvalidOperation, ValueError):
        return "needs_review"
    # Repeated payments of the same amount by the same player are legitimate.
    # Still allow only one credit per event ID and per deposit ticket.
    tickets = db.execute(
        "SELECT id,user_id,amount,message,created FROM tickets WHERE kind='deposit' AND status='open' AND amount=?",
        (amount,)).fetchall()
    matches = []
    for ticket in tickets:
        nick = re.search(r"\[MINECRAFT NICK\]\s+(\.?[A-Za-z0-9_]{3,16})(?![A-Za-z0-9_])",
                         ticket["message"])
        if (nick and nick.group(1).casefold() == player.casefold()
                and cutoff <= _deposit_time(ticket["created"]) <= receipt_time
                and (receipt_time - _deposit_time(ticket["created"])).total_seconds() <= 1800):
            matches.append(ticket)
    if len(matches) != 1:
        return "needs_review"
    ticket = matches[0]
    previous = db.execute(
        "SELECT amount,created FROM bot_deposit_credits WHERE user_id=?",
        (ticket["user_id"],)).fetchall()
    if amount + sum(p["amount"] for p in previous
                    if 0 <= (now() - _deposit_time(p["created"])).total_seconds() < 86400) > daily_limit:
        return "needs_review"
    if db.execute("SELECT event_id FROM bot_deposit_credits WHERE event_id=? OR ticket_id=?",
                  (event_id, ticket["id"])).fetchone():
        return "needs_review"
    changed = db.execute(
        "UPDATE tickets SET status='approved',response=?,handled=0 WHERE id=? AND status='open'",
        ("Automatically credited from bot event " + event_id, ticket["id"]))
    if changed.rowcount != 1:
        return "needs_review"
    db.execute("INSERT INTO bot_deposit_credits(event_id,ticket_id,user_id,amount) VALUES(?,?,?,?)",
               (event_id, ticket["id"], ticket["user_id"], amount))
    db.execute("UPDATE users SET balance=balance+? WHERE id=?", (amount, ticket["user_id"]))
    db.execute("UPDATE bot_payment_events SET status='credited' WHERE event_id=?", (event_id,))
    return "credited"


def create_session(db, uid):
    token = secrets.token_urlsafe(40)
    db.execute("INSERT INTO sessions(token_hash,user_id,expires) VALUES(?,?,?)",
               (hashlib.sha256(token.encode()).hexdigest(), uid,
                (now() + timedelta(days=365)).isoformat()))
    return token

