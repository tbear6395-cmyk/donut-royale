        if path == "/api/role":
            if user["role"] != "owner":
                return self.fail(403, "Only owner can change roles")
            uid, role = data.get("id"), data.get("role")
            if type(uid) is not int or uid == user["id"] or role not in ("admin", "player"):
                return self.fail(400, "Invalid role change")
