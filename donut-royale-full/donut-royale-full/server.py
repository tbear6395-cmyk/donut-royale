class Handler(BaseHTTPRequestHandler):
    def send_json(self, status, payload, cookie=None):
        data = json.dumps(payload, ensure_ascii=False, default=str).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(data)))
        self.send_header("Cache-Control", "no-store")
        self.send_header("X-Content-Type-Options", "nosniff")
        if cookie:
            self.send_header("Set-Cookie", cookie)
        self.end_headers()
        self.wfile.write(data)

    def fail(self, status, message):
        self.send_json(status, {"error": message})

    def payload(self):
        try:
            length = int(self.headers.get("Content-Length", "0"))
            if length < 0 or length > 20000:
                return {}
            data = json.loads(self.rfile.read(length))
            return data if isinstance(data, dict) else {}
        except (ValueError, UnicodeDecodeError):
            return {}

    def token(self):
        try:
            cookies = SimpleCookie()
            cookies.load(self.headers.get("Cookie", ""))
            return cookies["session"].value if "session" in cookies else None
        except Exception:
            return None

    def me(self):
        token = self.token()
        if not token:
            return None
        with db_open() as db:
            row = db.execute("""
                SELECT u.id,u.username,u.role,u.balance FROM sessions s
                JOIN users u ON u.id=s.user_id
                WHERE s.token_hash=? AND s.expires>?
            """, (hashlib.sha256(token.encode()).hexdigest(), now().isoformat())).fetchone()
        return dict(row) if row else None

    def cookie(self, token):
        cookie = "session=" + token + "; Path=/; HttpOnly; SameSite=Lax; Max-Age=31536000"
        if os.getenv("RENDER") or os.getenv("COOKIE_SECURE") == "1":
            cookie += "; Secure"
        return cookie

